#!/usr/bin/env python3
"""Generates src/Icon.r, the application's icon and Finder bundle resources,
from the pixel art in tools/icon.txt.

    python3 tools/make-icon.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, 'tools', 'icon.txt')
OUTPUT = os.path.join(ROOT, 'src', 'Icon.r')

CREATOR = 'TSmn'
OWNER_STRING = 'ThingSet Monitor'

# Colours of the logo (from thingset.io's apple-touch-icon.png).
RGB = {'K': (0x00, 0x00, 0x00), 'B': (0x00, 0x5E, 0x85), 'G': (0x80, 0x80, 0x80), 'W': (0xFF, 0xFF, 0xFF)}

# The standard 4-bit palette has no colour near the logo's blue, so pick by hand.
PALETTE_4 = {'K': 15, 'B': 6, 'G': 13, 'W': 0, '.': 0}


def system_palette_8():
    """The Mac OS 8-bit system palette: a 6x6x6 colour cube (less black), then
    ramps of red, green, blue and grey, then black."""
    colours = []
    for i in range(215):
        colours.append(tuple((5 - level) * 0x33 for level in (i // 36, i // 6 % 6, i % 6)))
    ramp = [0xEE, 0xDD, 0xBB, 0xAA, 0x88, 0x77, 0x55, 0x44, 0x22, 0x11]
    colours += [(v, 0, 0) for v in ramp] + [(0, v, 0) for v in ramp] + [(0, 0, v) for v in ramp]
    colours += [(v, v, v) for v in ramp] + [(0, 0, 0)]
    return colours


def nearest(colour, palette):
    return min(range(len(palette)), key=lambda i: sum((a - b) ** 2 for a, b in zip(colour, palette[i])))


def read_icons():
    icons, size = {}, None
    for line in open(SOURCE).read().splitlines():
        if not line.strip() or line.startswith('#'):
            continue
        if line.strip().isdigit():
            size = int(line)
            icons[size] = []
        else:
            icons[size].append(line.strip())
    for size, rows in icons.items():
        if len(rows) != size or any(len(row) != size for row in rows):
            raise SystemExit(f'{SOURCE}: the {size}x{size} icon must be {size} rows of {size} pixels')
        if set(''.join(rows)) - set('.KBGW'):
            raise SystemExit(f'{SOURCE}: unknown pixels {set("".join(rows)) - set(".KBGW")}')
    return icons


def bits(rows, test):
    """Packs rows into a 1-bit bitmap, most significant bit leftmost."""
    out = []
    for row in rows:
        value = 0
        for pixel in row:
            value = value << 1 | (1 if test(pixel) else 0)
        out.append(value.to_bytes(len(row) // 8, 'big'))
    return out


def nibbles(rows):
    out = []
    for row in rows:
        out.append(bytes(PALETTE_4[row[i]] << 4 | PALETTE_4[row[i + 1]] for i in range(0, len(row), 2)))
    return out


def indexed(rows, palette):
    index = {pixel: nearest(rgb, palette) for pixel, rgb in RGB.items()}
    index['.'] = 0
    return [bytes(index[pixel] for pixel in row) for row in rows]


def hex_lines(rows, indent):
    return '\n'.join(f'{indent}$"{row.hex().upper()}"' for row in rows)


def main():
    icons = read_icons()
    palette = system_palette_8()
    out = [
        '/*',
        ' * The application icon and Finder bundle. Generated by tools/make-icon.py',
        ' * from tools/icon.txt; edit that and regenerate rather than editing this.',
        ' */',
        '',
        '#include "Icons.r"',
        '#include "Finder.r"',
        '',
    ]
    for size, (mono, colour4, colour8) in ((32, ('ICN#', 'icl4', 'icl8')), (16, ('ics#', 'ics4', 'ics8'))):
        rows = icons[size]
        out += [
            f"resource '{mono}' (128) {{",
            '    {',
            '        /* icon: black, blue and grey are black */',
            hex_lines(bits(rows, lambda p: p in 'KBG'), '        ') + ',',
            '        /* mask */',
            hex_lines(bits(rows, lambda p: p != '.'), '        '),
            '    }',
            '};',
            '',
            f"resource '{colour4}' (128) {{",
            hex_lines(nibbles(rows), '    '),
            '};',
            '',
            f"resource '{colour8}' (128) {{",
            hex_lines(indexed(rows, palette), '    '),
            '};',
            '',
        ]
    out += [
        "resource 'FREF' (128) {",
        "    'APPL', 0, \"\"",
        '};',
        '',
        "resource 'BNDL' (128) {",
        f"    '{CREATOR}', 0,",
        '    {',
        "        'ICN#', { 0, 128 };",
        "        'FREF', { 0, 128 }",
        '    }',
        '};',
        '',
        '/* the owner resource, which names the application in Get Info */',
        f"data '{CREATOR}' (0, \"Owner resource\") {{",
        f'    $"{len(OWNER_STRING):02X}" "{OWNER_STRING}"',
        '};',
        '',
    ]
    with open(OUTPUT, 'w') as f:
        f.write('\n'.join(out))
    print(f'Wrote {os.path.relpath(OUTPUT, ROOT)}')


if __name__ == '__main__':
    main()
